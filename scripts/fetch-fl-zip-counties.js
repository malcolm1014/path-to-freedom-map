#!/usr/bin/env node
/* Fetches the US Census Bureau's 2020 ZCTA-to-County relationship file,
   filters it down to Florida, and writes FL_ZIP_COUNTY.js — a plain
   `const FL_ZIP_COUNTY = { "32601": "Alachua", ... }` map from 5-digit
   ZIP code to county name (matching this project's existing county-name
   spelling exactly, e.g. "DeSoto", "St. Johns", "Miami-Dade"), loaded the
   same no-build-step way as data.js/bus-data.js.

   WHY: the county picker's search box only matched county NAMES — someone
   who knows their ZIP code but not which county they're in (a real,
   common case for this app's audience) had no way to find themselves.

   SOURCE: https://www2.census.gov/geo/docs/maps-data/data/rel2020/zcta520/tab20_zcta520_county20_natl.txt
   — the Census Bureau's own official 2020 ZCTA5-to-county crosswalk
   (confirmed live via the relationship-files.2020.html page + the
   explanation PDF's file-naming convention), pipe-delimited, ~47.9K rows
   nationwide. A single ZCTA can straddle more than one county (e.g. ZCTA
   32008 spans Dixie/Gilchrist/Lafayette/Suwannee) — this script keeps
   only the county with the LARGEST land-area overlap (AREALAND_PART) per
   ZCTA, i.e. the county most of that ZIP's area is actually in, which is
   what "what county is ZIP X in" means for a human asking the question.

   No npm deps, matching this repo's existing scripts/ convention — a
   simple pipe-delimited split is safe here (verified no `|` or unescaped
   characters appear inside any field in this specific file).

   Run via `node scripts/fetch-fl-zip-counties.js` from the repo root.
   ZCTA boundaries don't change often (tied to the decennial census) —
   unlike bus-data.js this has no scheduled refresh workflow; re-run by
   hand if a newer vintage is ever needed. */

const fs = require('fs');
const path = require('path');

const SOURCE_URL = 'https://www2.census.gov/geo/docs/maps-data/data/rel2020/zcta520/tab20_zcta520_county20_natl.txt';
const OUT_PATH = path.join(__dirname, '..', 'FL_ZIP_COUNTY.js');
const FL_STATE_FIPS = '12';

async function main() {
  console.log(`[fetch-fl-zip-counties] downloading ${SOURCE_URL}`);
  const res = await fetch(SOURCE_URL);
  if (!res.ok) throw new Error(`download failed: HTTP ${res.status} ${res.statusText}`);
  const text = await res.text();
  const lines = text.split('\n');
  console.log(`[fetch-fl-zip-counties] downloaded ${lines.length} lines`);

  // best[zip] = { county, areaLandPart } — the largest-land-overlap county seen so far for this ZCTA
  const best = {};
  let flRowCount = 0;

  for (const line of lines) {
    if (!line || line.startsWith('OID_ZCTA5')) continue; // header or blank
    const cols = line.split('|');
    const zip = cols[1];
    const countyGeoid = cols[9];
    const countyNamelsad = cols[10];
    const areaLandPart = Number(cols[16]);
    if (!zip || !countyGeoid || !countyGeoid.startsWith(FL_STATE_FIPS)) continue;
    if (!countyNamelsad || !countyNamelsad.endsWith(' County')) continue; // Miami-Dade etc. all end this way in NAMELSAD
    flRowCount++;
    const countyName = countyNamelsad.slice(0, -' County'.length);
    const existing = best[zip];
    if (!existing || areaLandPart > existing.areaLandPart) {
      best[zip] = { county: countyName, areaLandPart };
    }
  }

  const flZipCounty = {};
  for (const zip of Object.keys(best).sort()) flZipCounty[zip] = best[zip].county;

  const zipCount = Object.keys(flZipCounty).length;
  const countiesRepresented = new Set(Object.values(flZipCounty)).size;
  if (zipCount < 900 || countiesRepresented < 60) {
    // Sanity floor: Florida has ~980 ZCTAs and 67 counties — a pull this
    // small means something upstream broke (a truncated download, a
    // format change), not a real result. Refuse to overwrite silently.
    throw new Error(`refusing to write FL_ZIP_COUNTY.js: only found ${zipCount} ZIPs across ${countiesRepresented} counties (expected ~980 ZIPs / 67 counties) — looks like a broken pull, not real data`);
  }

  const out = `// AUTO-GENERATED by scripts/fetch-fl-zip-counties.js -- do not hand-edit.\n// Maps a 5-digit FL ZIP code to its county (largest-land-overlap county per ZCTA).\n// Source: US Census Bureau 2020 ZCTA-to-County relationship file.\n// Regenerate with: node scripts/fetch-fl-zip-counties.js\nconst FL_ZIP_COUNTY = ${JSON.stringify(flZipCounty)};\n`;
  fs.writeFileSync(OUT_PATH, out);
  console.log(`[fetch-fl-zip-counties] wrote ${OUT_PATH} (${zipCount} ZIP codes across ${countiesRepresented} counties, ${(out.length / 1024).toFixed(0)}KB)`);
}

main().catch((err) => {
  console.error('[fetch-fl-zip-counties] FAILED:', err);
  process.exitCode = 1;
});
