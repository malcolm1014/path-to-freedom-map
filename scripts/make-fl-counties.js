// Build FL_COUNTY_GEO for path-to-freedom-map statewide drill-down.
// Source: US Census cartographic boundary file, 1:20,000,000 county polygons
//   (2010 vintage, same eric.clst.org mirror used for us-cyber-map/regions.js's
//   state polygons) — https://eric.clst.org/assets/wiki/uploads/Stuff/gz_2010_us_050_00_20m.json
// Filtered to STATE=12 (Florida), 67 counties.
//
// Douglas-Peucker simplified (same technique/tolerance defaults as
// us-cyber-map/scripts/make-regions.js) since the raw county-level rings are
// far more detailed than a statewide drill-down UI needs.
//
// Usage: node make-fl-counties.js <census-counties.json> FL_COUNTY_GEO.js [tol] [precision]
const fs = require('fs');

const SRC  = process.argv[2];
const OUT  = process.argv[3];
const TOL  = Number(process.argv[4] || 0.003);   // degrees (~330m) - finer than states since counties are smaller
const PREC = Number(process.argv[5] || 1000);    // 1000 => 3dp (~110 m)

function perpDist(p, a, b){
  const [px,py]=p, [ax,ay]=a, [bx,by]=b;
  const dx=bx-ax, dy=by-ay;
  if (dx===0 && dy===0) return Math.hypot(px-ax, py-ay);
  const t = ((px-ax)*dx + (py-ay)*dy) / (dx*dx+dy*dy);
  const cx = ax + Math.max(0,Math.min(1,t))*dx;
  const cy = ay + Math.max(0,Math.min(1,t))*dy;
  return Math.hypot(px-cx, py-cy);
}
function dp(pts, tol){
  if (pts.length < 3) return pts;
  let maxD=0, idx=0;
  for (let i=1;i<pts.length-1;i++){
    const d = perpDist(pts[i], pts[0], pts[pts.length-1]);
    if (d>maxD){ maxD=d; idx=i; }
  }
  if (maxD <= tol) return [pts[0], pts[pts.length-1]];
  return dp(pts.slice(0,idx+1), tol).slice(0,-1).concat(dp(pts.slice(idx), tol));
}
function simplifyRing(ring, tol){
  if (ring.length <= 5) return ring;
  const open = ring.slice(0, -1);
  let out = dp(open, tol);
  if (out.length < 3) out = open.filter((_,i)=> i % Math.ceil(open.length/3) === 0);
  return out.concat([out[0]]);
}

const round = c => Array.isArray(c[0]) ? c.map(round)
  : [Math.round(c[0]*PREC)/PREC, Math.round(c[1]*PREC)/PREC];

// Census cartographic files are latin-1, not utf-8 (same gotcha as the state file).
const src = JSON.parse(fs.readFileSync(SRC, 'latin1'));

const counties = [];
for (const f of src.features){
  if (f.properties.STATE !== '12') continue; // Florida only
  const name = f.properties.NAME;
  const fips = f.properties.COUNTY;
  const g = f.geometry;
  const polys = g.type === 'Polygon' ? [g.coordinates] : g.coordinates;
  const simplified = polys
    .map(poly => poly.map(ring => simplifyRing(ring, TOL)).filter(r => r.length >= 4))
    .filter(poly => poly.length > 0);
  counties.push({
    type:'Feature',
    properties:{ name, fips, censusArea: f.properties.CENSUSAREA },
    geometry:{ type:'MultiPolygon', coordinates: round(simplified) }
  });
}
counties.sort((a,b) => a.properties.name.localeCompare(b.properties.name));

const out = `/* Generated by scripts/make-fl-counties.js from the US Census cartographic
   boundary file gz_2010_us_050_00_20m.json (Douglas-Peucker simplified,
   tolerance ${TOL} deg). All 67 Florida counties for the statewide
   drill-down UI. Not a replacement for boundary.js's precise Hernando
   County outline (2068 vertices, TIGERweb-sourced) - that stays as the
   detailed home-county reference; this is the coarser statewide layer. */
const FL_COUNTY_GEO = ${JSON.stringify({type:'FeatureCollection', features:counties})};
`;
fs.writeFileSync(OUT, out);
const verts = counties.reduce((s,f)=>s+f.geometry.coordinates.flat(2).length, 0);
console.log('wrote', OUT, (out.length/1024).toFixed(0)+'KB,', counties.length, 'counties,', verts, 'vertices');
